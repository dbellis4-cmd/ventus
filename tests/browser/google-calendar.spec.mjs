import { test, expect } from "@playwright/test";

test("calendar preferences remain editable and the Calendar link opens Google in a new tab", async ({ page }) => {
  await fetch("http://127.0.0.1:3174/__reset");
  await page.goto("/login");
  await page.getByLabel("Email").fill("fixture@ventus.test");
  await page.getByLabel("Password").fill("fixture-password");
  await page.getByRole("button", { name: "Log in" }).click();
  await expect(page.getByRole("heading", { name: "Dashboard" })).toBeVisible();
  const calendar = page.getByRole("link", { name: /Calendar.*opens Google Calendar in a new tab/ });
  await expect(calendar).toHaveAttribute("target", "_blank");
  await expect(calendar).toHaveAttribute("href", "https://calendar.google.com/");
  await page.getByRole("button", { name: "Settings" }).click();
  await expect(page.getByRole("heading", { name: "Google Calendar" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Connect Google Calendar" })).toBeDisabled();
  await page.goto("/?calendar=already-connected");
  await page.getByRole("button", { name: "Settings" }).click();
  await expect(page.getByRole("status").filter({ hasText: "This Google account" })).toHaveText("This Google account is already connected to another Ventus account. Please use a different Google account.");
  await page.getByRole("button", { name: "Dashboard" }).click();
  await page.goto("/?date=2026-10-22");
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  let dialog = page.getByRole("dialog", { name: "New task" });
  const preference = dialog.getByRole("checkbox", { name: "Add to Google Calendar" });
  await dialog.getByLabel("Category").selectOption({ label: "Assignments" });
  await expect(preference).toBeChecked();
  await preference.uncheck();
  await expect(preference).not.toBeChecked();
  await dialog.getByLabel("Category").selectOption({ label: "Meetings" });
  await expect(preference).toBeChecked();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Research Paper" }).click();
  dialog = page.getByRole("dialog", { name: "Edit task" });
  await expect(dialog.getByRole("checkbox", { name: "Add to Google Calendar" })).toBeChecked();
  await dialog.getByRole("checkbox", { name: "Add to Google Calendar" }).uncheck();
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await page.reload();
  await page.getByRole("button", { name: "Research Paper" }).click();
  await expect(page.getByRole("dialog", { name: "Edit task" }).getByRole("checkbox", { name: "Add to Google Calendar" })).not.toBeChecked();
});
